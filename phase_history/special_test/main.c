static void servo_set(int us)
{
  if (us < SERVO_MIN_US) us = SERVO_MIN_US;   // 물리 한계 보호
  if (us > SERVO_MAX_US) us = SERVO_MAX_US;
  __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_3, (uint32_t)us);  // 1틱 = 1µs
}

static void motor_set(int pwm)
{
  if (pwm >  MOTOR_PWM_MAX) pwm =  MOTOR_PWM_MAX;
  if (pwm < -MOTOR_PWM_MAX) pwm = -MOTOR_PWM_MAX;

  if (pwm > 0) {            // 정방향  IN1=H IN2=L
    HAL_GPIO_WritePin(GPIOA, GPIO_PIN_1, GPIO_PIN_SET);
    HAL_GPIO_WritePin(GPIOA, GPIO_PIN_4, GPIO_PIN_RESET);
  } else if (pwm < 0) {     // 역방향  IN1=L IN2=H
    HAL_GPIO_WritePin(GPIOA, GPIO_PIN_1, GPIO_PIN_RESET);
    HAL_GPIO_WritePin(GPIOA, GPIO_PIN_4, GPIO_PIN_SET);
  } else {                  // 정지    둘 다 L
    HAL_GPIO_WritePin(GPIOA, GPIO_PIN_1, GPIO_PIN_RESET);
    HAL_GPIO_WritePin(GPIOA, GPIO_PIN_4, GPIO_PIN_RESET);
  }
  __HAL_TIM_SET_COMPARE(&htim2, TIM_CHANNEL_1, (uint32_t)abs(pwm));
}

/* USART2 1바이트 수신 완료마다 호출 (인터럽트 문맥 — 짧게 끝낸다) */
void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
  if (huart->Instance != USART2) return;

  if (rx_byte == '\n' || rx_byte == '\r') {
    if (rx_idx > 0) {
      rx_buf[rx_idx] = '\0';
      int s, a;
      if (sscanf(rx_buf, "%d,%d", &s, &a) == 2) {   // "speed,angle"
        g_speed    = s;
        g_angle    = a;
        g_last_cmd = HAL_GetTick();                  // 워치독 리셋
        HAL_GPIO_TogglePin(GPIOA, LD2_Pin);          // 받을 때마다 LED
      }
      rx_idx = 0;
    }
  } else if (rx_idx < sizeof(rx_buf) - 1) {
    rx_buf[rx_idx++] = (char)rx_byte;
  }

  HAL_UART_Receive_IT(&huart2, &rx_byte, 1);         // 다음 바이트 장전
}

/* 프레이밍/오버런 에러가 나도 수신을 다시 건다 */
void HAL_UART_ErrorCallback(UART_HandleTypeDef *huart)
{
  if (huart->Instance == USART2)
    HAL_UART_Receive_IT(&huart2, &rx_byte, 1);
}



